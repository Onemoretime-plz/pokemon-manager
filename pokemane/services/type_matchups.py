def get_single_type_multiplier(attack_type, defense_type):
    """
    単タイプに対する倍率を返す。
    未定義の場合は等倍。
    """
    return TYPE_EFFECTIVENESS.get(attack_type, {}).get(defense_type, 1)


def get_type_multiplier(attack_type, defender_type1, defender_type2=None):
    """
    複合タイプを考慮した倍率を返す。
    """
    multiplier = get_single_type_multiplier(attack_type, defender_type1)

    if defender_type2:
        multiplier *= get_single_type_multiplier(attack_type, defender_type2)

    return multiplier


def apply_ability_type_effect(multiplier, attack_type, ability_name):
    """
    特性によるタイプ相性補正を反映する。

    無効系：倍率を0にする
    半減系：元の倍率に0.5をかける
    """
    effects = ABILITY_TYPE_EFFECTS.get(ability_name)

    if not effects:
        return multiplier

    if attack_type not in effects:
        return multiplier

    effect = effects[attack_type]

    if effect == 0:
        return 0

    return multiplier * effect


def calculate_defensive_multiplier(attack_type, pokemon, ability_name):
    """
    指定した攻撃タイプが、対象ポケモンに何倍で通るかを返す。

    pokemon:
    - type1
    - type2

    ability_name:
    - 型に登録された特性名
    """
    multiplier = get_type_multiplier(
        attack_type,
        pokemon.type1,
        pokemon.type2,
    )

    multiplier = apply_ability_type_effect(
        multiplier,
        attack_type,
        ability_name,
    )

    return multiplier